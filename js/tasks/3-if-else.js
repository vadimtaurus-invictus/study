// ==================   6    Складання іспиту

// 1. Отримуємо оцінку від користувача
const scoreInput = prompt("Введіть оцінку студента (від 0 до 100):");

// 2. Перетворюємо введене значення у число
const score = Number(scoreInput);

// 3. Перевіряємо умову за допомогою if-else  // з перевіркою:
// 1- (isNAN) - чи це номер
// 2-  null -результат коли натиснуто кнопку "Скасувати"
// 3-  trim - видаляє пробіли з обох кінців рядка
if (isNaN(score) || scoreInput === null || scoreInput.trim() === "") {
  alert("Помилка: будь ласка, введіть коректне число!");
} else if (score < 0 || score > 100) {
  alert("Помилка: оцінка має бути в межах від 0 до 100.");
} else if (score >= 60) {
  alert(`Вітаємо! Студент склав іспит з результатом ${score} балів.`);
} else {
  alert(`На жаль, іспит не складено. Результат: ${score} балів.`);
}

//===================7 перевірка на високосність проста (виведення в консоль закоментовано)

// 1. Запитуємо у користувача рік та перетворюємо введене значення у число
const yEar = Number(prompt("Введіть рік для перевірки:"));

// 2. Перевіряємо, чи є введене значення коректним числом
if (isNaN(yEar)) {
  console.log("Будь ласка, введіть коректне числове значення.");
} else {
  // 3. Перевіряємо умову високосного року за допомогою оператора % (остача від ділення)
  if (yEar % 4 === 0) {
    // console.log(`${yEar} — це високосний рік.`);
    alert(`${yEar} — це високосний рік.`);
  } else {
    // console.log(`${yEar} — це звичайний (невисокосний) рік.`);
    alert(`${yEar} — це звичайний (невисокосний) рік.`);
  }
}

// ==================  8   перевірка на високосність повна (виведення в консоль закоментовано)

// 1. Запитуємо у користувача рік через спливаюче вікно
const input = prompt("Введіть рік для перевірки (наприклад, 2024):");

// Перетворюємо введене значення у ціле число
const year = parseInt(input);

// 2. Перевіряємо, чи користувач ввів саме число
if (isNaN(year)) {
  alert("Помилка! Будь ласка, введіть коректне число.");
} else {
  // 3. Основна логіка перевірки через if-else:
  // Рік є високосним, якщо він ділиться на 4 без остачі,
  // АЛЕ не ділиться на 100, ХІБА ЩО він також ділиться на 400.
  if ((year % 4 === 0 && year % 100 !== 0) || year % 400 === 0) {
    alert(`${year} — це високосний рік! 📅`); // вивід у вікно
    // console.log(`${year} — це високосний рік!`);   // вивід у консоль
  } else {
    alert(`${year} — це НЕ високосний рік. 📭`);
  }
}

// ==================   9   Привітання задежно від часу доби

// 1. Запитуємо годину у користувача та перетворюємо введене значення у число
const hourInput = prompt("Введіть годину (від 0 до 23):");
const hour = Number(hourInput);

// 2. Перевіряємо, чи ввів користувач коректне число від 0 до 23
if (isNaN(hour) || hour < 0 || hour > 23) {
  alert("Будь ласка, введіть коректне число від 0 до 23!");
} else {
  // 3. Визначаємо час доби за допомогою умовних операторів
  let greeting = "";

  if (hour >= 5 && hour < 12) {
    greeting = "Доброго ранку!";
  } else if (hour >= 12 && hour < 18) {
    greeting = "Доброго дня!";
  } else if (hour >= 18 && hour < 23) {
    greeting = "Доброго вечора!";
  } else {
    // Сюди потрапляє проміжок від 23:00 до 4:59 включно
    greeting = "Доброї ночі!";
  }

  // 4. Виводимо привітання
  alert(greeting);
}
