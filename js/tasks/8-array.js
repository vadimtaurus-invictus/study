console.log("=========Фільтрація за умовою================№19");

// 1. Масив об'єктів
const peopLe = [
  { name: "Анна", age: 19 },
  { name: "Олексій", age: 25 },
  { name: "Марія", age: 20 },
  { name: "Дмитро", age: 32 },
  { name: "Софія", age: 17 },
];

