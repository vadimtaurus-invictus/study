// ******************************* -нагадування про індекси-**********************************

// Індекси в JS починаються з 0:  масив  - [10,20,30,40,50,60]
// [0] = 10 (1-й), [1] = 20 (2-й), [2] = 30 (3-й), [3] = 40 (4-й), [4] = 50 (5-й), [5] = 60 (6-й)

console.log("=========Додавання елементів у кінець================№1");

// 1. Масив
const numbers = [5, 12, 7];

// 2. Додаємо число 10 у кінець масиву  **push**
numbers.push(10);

// 3. Виводимо
console.log(numbers); // [5, 12, 7, 10]

console.log("=========Видалення останнього елемента================№2");

// 1. масив з п'яти різних чисел
const numberS = [12, 45, 7, 89, 23];

// 2. Видаляємо останній елемент за допомогою методу **pop()**
// Метод pop() видаляє останній елемент і повертає його значення
const removedElement = numberS.pop();

// 3. Виводимо в консоль
console.log("Видалений елемент:", removedElement); // 23
console.log("Оновлений масив:", numberS); // [12, 45, 7, 89]

console.log("=========Додавання елементів на початок================№3");

// 1. Створюємо масив із двох рядків
const list = ["Apple", "Orange"];

// 2. Додаємо "Start" на початок масиву  **unshift**
list.unshift("Start");

// 3. Виводимо масив у консоль
console.log(list); // ['Start', 'Apple', 'Orange']

console.log("=========Видалення першого елемента================№4");

// 1. Створюємо масив із п'яти чисел
const numbeRs = [10, 20, 30, 40, 50];

// 2. Видаляємо перший елемент за допомогою **shift()**
const removedElemenT = numbeRs.shift();

// 3. Виводимо результати у консоль
console.log("Оновлений масив:", numbeRs); // [20, 30, 40, 50]
console.log("Видалений елемент:", removedElemenT); // 10

console.log("=========Витягнення частини масиву================№5");

// 1. Створюємо масив із шести чисел
const originalArray = [10, 20, 30, 40, 50, 60];

// 2. Використовуємо **slice** для копіювання елементів
// slice(2, 5) бере елементи з індексу 2 до 5 (не включаючи 5-й індекс)
const newArray = originalArray.slice(2, 5);

// 3. Виводимо новий масив у консоль
console.log(newArray); // [30, 40, 50]

console.log("=========Заміна елементів================№6");

// 1. Створюємо масив із 7 чисел
const numbErs = [10, 20, 30, 40, 50, 60, 70];

// 2. Видаляємо 3-й та 4-й елементи (індекси 2 та 3)
// і вставляємо на їх місце два нових значення (наприклад, 99 та 100)
numbErs.splice(2, 2, 99, 100);

// 3. Виводимо оновлений масив у консоль
console.log(numbErs);
// Результат: [10, 20, 99, 100, 50, 60, 70]

console.log("=========Об’єднання масивів================№7");

// 1. Створюємо два масиви з числами
const numbers1 = [1, 2, 3, 4];
const numbers2 = [5, 6, 7, 8];

// 2. Об’єднуємо їх за допомогою методу **concat()**
const combinedNumbers = numbers1.concat(numbers2);

// 3. Виводимо результат у консоль
console.log(combinedNumbers);
// В консолі буде: [1, 2, 3, 4, 5, 6, 7, 8]

console.log("=========Пошук індексу================№8");

// 1. масив із 5 імен
const names = ["Олена", "Андрій", "Марія", "Максим", "Софія"];

// 2. Шукаємо індекс імені 'Марія'
const targetName = "Марія";
const index = names.indexOf(targetName);

// 3. Вивід індексу в консоль
console.log(`Індекс імені "${targetName}" у масиві:`, index); // Індекс імені "Марія" у масиві: 2

console.log("=========Переворот масиву================№9");

// 1. Масив
const numBers = [10, 20, 30, 40];

// 2. Розворот масиву за допомогою методу **reverse()**
numBers.reverse();

// 3. Вивід консоль
console.log(numBers); // [40, 30, 20, 10]

console.log("=========Створення рядка з масиву================№10");

// 1. Масив із 5-ти слів
const words = ["яблуко", "банан", "груша", "апельсин", "слива"];

// 2. Об'єднуємо елементи масиву в один рядок метод **join(", ")** розділений комами
const result = words.join(", ");

// 3. результат у консоль
console.log(result); // яблуко, банан, груша, апельсин, слива
