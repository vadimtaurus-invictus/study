// ================5   Перевірка пароля

// 1. Задаємо правильний пароль
const correctPassword = "123456";

// 2. Ініціалізуємо лічильник спроб
let attempts = 3;

// Змінна для відстеження, чи пароль введено правильно
let accessGranted = false;

// Цикл виконується, поки залишаються спроби і пароль ще не вгадано
while (attempts > 0 && !accessGranted) {
  // Просимо користувача ввести пароль (показуємо, скільки спроб залишилось)
  const userPassword = prompt(`Введіть пароль. Залишилось спроб: ${attempts}`);

  // Перевіряємо введене значення
  if (userPassword === correctPassword) {
    accessGranted = true; // Змінюємо прапорець, щоб вийти з циклу
  } else {
    attempts--; // Якщо неправильно, зменшуємо кількість спроб
    if (attempts > 0) {
      alert("Неправильний пароль. Спробуйте ще раз.");
    }
  }
}

// 3. Фінальна перевірка результату після виходу з циклу
if (accessGranted) {
  alert("Доступ надано");
} else {
  alert("Доступ заблоковано");
}

