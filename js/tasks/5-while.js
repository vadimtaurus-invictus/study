console.log("Числа Фібоначчі");

// Запитуємо у користувача кількість чисел N
const n1 = Number(prompt("Введіть кількість чисел Фібоначчі (N):"));

if (isNaN(n) || n1 <= 0) {
  console.log("Будь ласка, введіть коректне число більше 0.");
} else {
  // Перші два числа послідовності оголошуємо вручну
  let a = 0;
  let b = 1;

  let result = []; // Масив для збору чисел, щоб вивести їх рядком
  let count = 0; // Лічильник для циклу while

  while (count < n1) {
    if (count === 0) {
      result.push(a); // Додаємо перше число (0)
    } else if (count === 1) {
      result.push(b); // Додаємо друге число (1)
    } else {
      // Обчислюємо наступне число як суму двох попередніх
      const next = a + b;
      result.push(next);

      // Зсуваємо змінні: тепер 'a' стає колишнім 'b', а 'b' стає новим 'next'
      a = b;
      b = next;
    }

    count++; // Збільшуємо лічильник, щоб цикл не став безкінечним
  }

  // Виводимо результат у консоль та через alert
  console.log(`Перші ${n1} чисел Фібоначчі:`, result.join(", "));
  alert(`Перші ${n1} чисел Фібоначчі:\n${result.join(", ")}`);
}
