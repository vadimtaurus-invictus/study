console.log("Пошук дільників числа");
// ------------------------------

// 1. Запитуємо у користувача додатне число
const nUmber = Number(prompt("Введіть додатне! число для пошуку дільника:"));

// Створюємо масив, куди будемо зберігати знайдені дільники
const divisors = [];

// 2. Шукаємо всі числа, на які воно ділиться без остачі
// Перебираємо всі числа від 1 до самого введеного числа
for (let i = 1; i <= nUmber; i++) {
  if (nUmber % i === 0) {
    divisors.push(i); // Якщо ділиться без остачі, додаємо в масив
  }
}

// 3. Виводимо список всіх дільників
console.log(`Дільники числа ${nUmber}:`, divisors.join(", "));
