// 1. Запитуємо у користувача кількість чисел N
const n7 = parseInt(prompt("Введіть кількість чисел Фібоначчі (N):"));

if (isNaN(n7) || n7 <= 0) {
  console.log("Будь ласка, введіть коректне додатне число.");
} else {
  // Створюємо масив і вручну оголошуємо перші два числа
  const fibonacci = [0, 1];

  // 2. Використовуємо цикл for для обчислення решти чисел
  // Починаємо з індексу 2, оскільки індекси 0 і 1 вже зайняті
  for (let i = 2; i < n7; i++) {
    // Кожне наступне число — це сума двох попередніх
    fibonacci[i] = fibonacci[i - 1] + fibonacci[i - 2];
  }

  // Оскільки користувач міг ввести N = 1, обрізаємо масив до потрібної довжини N
  const result = fibonacci.slice(0, n7);

  // 3. Виводимо результат
  console.log(`Перші ${n7} чисел Фібоначчі:`, result.join(", "));
}
