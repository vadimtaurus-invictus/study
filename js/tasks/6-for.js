console.log("Порахувати кількість чисел, які діляться на 3 (1 - 50)");
// --------------------------
// Створюємо змінну-лічильник для збереження кількості чисел
let count = 0;

// Запускаємо цикл від 1 до 50 включно
for (let i = 1; i <= 50; i++) {
  // Перевіряємо, чи ділиться число на 3 без залишку
  if (i % 3 === 0) {
    count++; // Збільшуємо лічильник на 1
  }
}

// Виводимо фінальний результат у консоль
console.log(
  "Кількість чисел від 1 до 50, що діляться на 3 без залишку:",
  count,
);
// +++++++++++++++++++++++++++++++++++++++++++++++F2 для папралельної заміни назв змінних
//    в середині циклу змінні можуть мати однакові назви з попередніми прикладами де вони використовуються
// ======================================================5  Пароль

const correctPassword = "123456"; // Правильний пароль
const attempts = 3; // Кількість доступних спроб
let accessGranted = false; // Прапорець для відстеження успіху

for (let i = 1; i <= attempts; i++) {
  // Запитуємо пароль у користувача
  const userPassword = prompt(`Спроба ${i} із ${attempts}. Введіть пароль:`);

  // Перевіряємо, чи правильний пароль
  if (userPassword === correctPassword) {
    alert("Доступ надано");
    accessGranted = true;
    break; // Перериваємо цикл, бо пароль вгадано
  }

  // Повідомляємо про помилку, якщо це не остання спроба
  if (i < attempts) {
    alert("Неправильний пароль. Спробуйте ще раз.");
  }
}

// Якщо після закінчення циклу доступ так і не надано
if (!accessGranted) {
  alert("Доступ заблоковано");
}

