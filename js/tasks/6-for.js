// 1. Запитуємо у користувача число n
const n = Number(prompt("ВВедіть кількість чисел для підрахунку їх суми:"));

// Перевіряємо, чи користувач ввів коректне число
if (isNaN(n) || n < 1) {
  console.log("Будь ласка, введіть ціле позитивне число.");
} else {
  // 2. Створюємо змінну для зберігання суми
  let sum = 0;

  // 3. Запускаємо цикл for від 1 до n
  for (let c = 1; c <= n; c++) {
    sum += c; // Додаємо поточне число до загальної суми
  }

  // 4. Виводимо результат
  //   console.log(`Сума чисел від 1 до ${n} дорівнює: ${sum}`);
  alert(`Сума чисел від 1 до ${n} дорівнює: ${sum}`);
}

