<?php
$text = "  Це   речення  з   великою    кількістю   зайвих   пробілів.  ";

// Замінюємо будь-яку послідовність пробілів на один пробіл та обрізаємо краї
$cleanText = trim(preg_replace('/\s+/', ' ', $text));

echo $cleanText;    // Результат: "Це речення з великою кількістю зайвих пробілів."


echo "<br>";
echo "<hr>";

// **********************  2 ***************************

$text2 = " речення де кожне слово починається з великої літери";

// Робимо першу літеру кожного слова великою з урахуванням UTF-8
$resultText = mb_convert_case($text2, MB_CASE_TITLE, "UTF-8");

echo $resultText;   //Речення Де Кожне Слово Починається З Великої Літери

echo "<br>";
echo "<hr>";

// **********************  3  **********************

$text = "Привіт, світе! Це — приклад речення: з комою, крапкою... та тире.";

// Шукаємо всі послідовності літер, ігноруючи знаки пунктуації та пробіли
preg_match_all('/[\p{L}]+/u', $text, $matches);

// Масив знайдених слів
$words = $matches[0];

print_r($words);   // Array ( [0] => Привіт 
                              // [1] => світе 
                             // [2] => Це 
                             //[3] => приклад 
                             //[4] => речення 
                             //[5] => з 
                             //[6] => комою 
                             //[7] => крапкою 
                             //[8] => та 
                             //[9] => тире )
